#!/usr/bin/env python3
"""news-image-20261124 entry program.

Copies the image shipped beside this file (entry.png) to the output
directory, as entry.png. Standard library only.

The output directory comes from MAKEFUN_OUTPUT_DIR, defaulting to /output.
"""
import os
import shutil
import sys


def main() -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    source = os.path.join(here, "entry.png")
    if not os.path.isfile(source):
        print("entry.png not found beside main.py", file=sys.stderr)
        return 1
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    shutil.copyfile(source, os.path.join(out_dir, "entry.png"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
